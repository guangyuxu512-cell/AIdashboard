export type VisualTokenGroupKey =
  | 'card'
  | 'summary'
  | 'runtime'
  | 'capability'
  | 'global'
  | 'control'
  | 'typography'

export type VisualTokenUnit = 'px' | '%' | ''

export type VisualColorTokenGroupKey =
  'surface' | 'text' | 'status' | 'selected'

export type VisualColorTheme = 'light' | 'dark'

export interface VisualTokenGroup {
  key: VisualTokenGroupKey
  label: string
  description: string
}

export interface VisualTokenDefinition {
  key: string
  cssVar: `--${string}`
  label: string
  group: VisualTokenGroupKey
  defaultValue: number
  min: number
  max: number
  step: number
  unit: VisualTokenUnit
  description: string
  warning?: (value: number) => string | null
}

export interface VisualColorTokenGroup {
  key: VisualColorTokenGroupKey
  label: string
  description: string
}

export interface VisualColorContrastTarget {
  cssVar: `--${string}`
  minimumRatio: number
  label: string
}

export interface VisualColorTokenDefinition {
  key: string
  cssVar: `--${string}`
  label: string
  group: VisualColorTokenGroupKey
  theme: VisualColorTheme
  description: string
  contrastTarget?: VisualColorContrastTarget
}

export type VisualAppearanceTokenGroupKey = 'radius' | 'border' | 'shadow'

export interface VisualAppearanceTokenGroup {
  key: VisualAppearanceTokenGroupKey
  label: string
  description: string
}

/**
 * Stage 3B Appearance Token 只描述可见外观，不参与 Stage 2 尺寸、间距或字体基线。
 * shadow Token 以主题隔离；Radius 与视觉 Border 在 Light / Dark 间共用。
 */
export interface VisualAppearanceTokenDefinition {
  key: string
  cssVar: `--${string}`
  label: string
  group: VisualAppearanceTokenGroupKey
  defaultValue: number
  min: number
  max: number
  step: number
  unit: VisualTokenUnit
  description: string
  theme?: VisualColorTheme
}

/**
 * 颜色条目的语义模板只维护一次；Light / Dark 由运行时基于同一模板展开。
 * Hex 默认值仍只存在于 tokens.css，不在调参器 Registry 复制颜色事实。
 */
interface VisualColorTokenTemplate {
  key: string
  cssVar: `--${string}`
  label: string
  group: VisualColorTokenGroupKey
  description: string
  contrastTarget?: VisualColorContrastTarget
}

